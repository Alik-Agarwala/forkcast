"""Deterministic hashing used for bucketing.

INVARIANT: this must produce exactly the same numbers as ``src/core/hash.ts``.
Python and JavaScript services that share a Forkcast server must put every
user in the same bucket, otherwise one person could see ``T1`` on the website
and ``C`` from the API. ``tests/test_parity.py`` checks this against vectors
generated by the JS implementation.
"""

from __future__ import annotations

#: Number of buckets. 10,000 buckets = 0.01% allocation granularity.
BUCKETS = 10_000

_MASK = 0xFFFFFFFF
_C1 = 0xCC9E2D51
_C2 = 0x1B873593


def _utf8(value: str) -> bytes:
    try:
        return value.encode("utf-8")
    except UnicodeEncodeError:
        # Lone surrogates: TextEncoder in JS replaces them with U+FFFD.
        fixed = "".join("�" if 0xD800 <= ord(ch) <= 0xDFFF else ch for ch in value)
        return fixed.encode("utf-8")


def _rotl(x: int, r: int) -> int:
    return ((x << r) | (x >> (32 - r))) & _MASK


def murmur3(value: str, seed: int = 0) -> int:
    """MurmurHash3 (x86, 32-bit) over the UTF-8 bytes of ``value``."""
    data = _utf8(value)
    length = len(data)
    nblocks = length >> 2
    h = seed & _MASK

    for i in range(nblocks):
        o = i << 2
        k = data[o] | (data[o + 1] << 8) | (data[o + 2] << 16) | (data[o + 3] << 24)
        k = (k * _C1) & _MASK
        k = _rotl(k, 15)
        k = (k * _C2) & _MASK
        h ^= k
        h = _rotl(h, 13)
        h = (h * 5 + 0xE6546B64) & _MASK

    k = 0
    tail = nblocks << 2
    rem = length & 3
    if rem == 3:
        k ^= data[tail + 2] << 16
    if rem >= 2:
        k ^= data[tail + 1] << 8
    if rem >= 1:
        k ^= data[tail]
        k = (k * _C1) & _MASK
        k = _rotl(k, 15)
        k = (k * _C2) & _MASK
        h ^= k

    h ^= length
    h ^= h >> 16
    h = (h * 0x85EBCA6B) & _MASK
    h ^= h >> 13
    h = (h * 0xC2B2AE35) & _MASK
    h ^= h >> 16
    return h


def bucket_of(namespace: str, user_id: str) -> int:
    """Map ``(namespace, user_id)`` to a stable bucket in ``[0, BUCKETS)``."""
    return murmur3(f"{namespace}:{user_id}") % BUCKETS
